/**
* @brief Function implementing the TimeBasedTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartTimeBasedTask */
void StartTimeBasedTask(void *argument)
{
  /* USER CODE BEGIN 5 */
  /* Infinite loop */

	RTC_TimeTypeDef sTime;
	RTC_DateTypeDef sDate; // You must read Date after Time to unlock the RTC registers

	uint32_t morning_start = 7 * 3600;           // 07:00:00
	uint32_t morning_end   = 7 * 3600 + 25;      // 07:00:19
	uint32_t noon_start = 15 * 3600 + 25;           // 15
	uint32_t noon_end   = 15 * 3600 + 50;      // 15
	uint32_t evening_start = 22.5 * 3600 + 50;     // 22:30:19 (14 hours after morning end)
	uint32_t evening_end   = 22.5 * 3600 + 75;     // 22:30:38

	for(;;) {
	  HAL_RTC_GetTime(&hrtc, &sTime, RTC_FORMAT_BIN);
	  HAL_RTC_GetDate(&hrtc, &sDate, RTC_FORMAT_BIN);

	  uint32_t now = (sTime.Hours * 3600) + (sTime.Minutes * 60) + sTime.Seconds;

	  if (now >= morning_start && now < morning_end) {
		  // 08:00:00 to 08:00:20 -> RESET, SET, SET
		  HAL_GPIO_WritePin(LampsRelay_GPIO_Port, LampsRelay_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpA_GPIO_Port, PumpA_Pin, GPIO_PIN_SET);
		  HAL_GPIO_WritePin(PumpB_GPIO_Port, PumpB_Pin, GPIO_PIN_SET);
	  }
	  else if (now >= morning_end && now < noon_start) {
		  // 08:00:20 to 15:00 -> RESET, RESET, RESET
		  HAL_GPIO_WritePin(LampsRelay_GPIO_Port, LampsRelay_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpA_GPIO_Port, PumpA_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpB_GPIO_Port, PumpB_Pin, GPIO_PIN_RESET);
	  }
	  else if (now >= noon_start && now < noon_end) {
		  // 15:00:25 - 15:00:50
		  HAL_GPIO_WritePin(LampsRelay_GPIO_Port, LampsRelay_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpA_GPIO_Port, PumpA_Pin, GPIO_PIN_SET);
		  HAL_GPIO_WritePin(PumpB_GPIO_Port, PumpB_Pin, GPIO_PIN_SET);
	  }
	  else if (now >= noon_end && now < evening_start) {
		  // 15:00:50 - 22:30:50
		  HAL_GPIO_WritePin(LampsRelay_GPIO_Port, LampsRelay_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpA_GPIO_Port, PumpA_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpB_GPIO_Port, PumpB_Pin, GPIO_PIN_RESET);
	  }
	  else if (now >= evening_start && now < evening_end) {
		  // 22:30:50 - 22:31:15 -> RESET, SET, SET
		  HAL_GPIO_WritePin(LampsRelay_GPIO_Port, LampsRelay_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpA_GPIO_Port, PumpA_Pin, GPIO_PIN_SET);
		  HAL_GPIO_WritePin(PumpB_GPIO_Port, PumpB_Pin, GPIO_PIN_SET);
	  }
	  else {
		  // All other times (22:31:15 until 07:59:59) -> SET, RESET, RESET
		  HAL_GPIO_WritePin(LampsRelay_GPIO_Port, LampsRelay_Pin, GPIO_PIN_SET);
		  HAL_GPIO_WritePin(PumpA_GPIO_Port, PumpA_Pin, GPIO_PIN_RESET);
		  HAL_GPIO_WritePin(PumpB_GPIO_Port, PumpB_Pin, GPIO_PIN_RESET);
	  }
	  osDelay(1000); // Check every 1 second
	}
  /* USER CODE END 5 */
}

